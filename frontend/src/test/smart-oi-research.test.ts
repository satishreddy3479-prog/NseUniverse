// Research run: the divergence indicators over the stored sessions, with the forward move after each signal against the move after any candle.
// Skipped unless SMARTOI_RESEARCH_DIR points at the folder written by scripts/smart-oi-export.py. SMARTOI_RESEARCH_OUT is where the report is written.
//   SMARTOI_RESEARCH_DIR=... SMARTOI_RESEARCH_OUT=../docs/smart-oi-research.md npx vitest run src/test/smart-oi-research.test.ts
// Nothing here changes what the page shows: it only measures. Signals are taken at the candle they are confirmed on (their state at that moment, not
// whether they later failed), so no future information leaks into the result.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { smartOiCandles, type SmartOiSeries } from "../lib/optionTools";
import { alignFuture, analyseSmartOi, buildStrikeFlow, candlesFor, composeOf, INDICATOR_NAMES, TH, type Reading, type Signal } from "../lib/smartOiDivergence";
import type { FuturesSeries, StrikeSeries } from "../lib/types";

const DIR = process.env.SMARTOI_RESEARCH_DIR;
const OUT = process.env.SMARTOI_RESEARCH_OUT;
const HORIZONS = [15, 30, 60] as const; // minutes after the signal
const TFS = [3, 5] as const;

interface DayFile { day: string; expiry: string; atm: number | null; oi: SmartOiSeries; strikes: StrikeSeries | null; future: FuturesSeries | null }
interface Obs { day: string; id: string; dir: "bullish" | "bearish" | "neutral"; ret: Record<number, number | null> }

/** Wilson 95 % interval for a share. */
const wilson = (k: number, n: number): [number, number] => {
  if (n === 0) return [0, 1];
  const z = 1.96, p = k / n, d = 1 + (z * z) / n, c = p + (z * z) / (2 * n), a = z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n));
  return [(c - a) / d, (c + a) / d];
};
const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null);
const bp = (v: number | null) => (v == null ? "—" : `${(v * 1e4).toFixed(1)}`);
const pc = (v: number | null) => (v == null ? "—" : `${(v * 100).toFixed(0)}%`);

describe.skipIf(!DIR)("Smart OI divergence research", () => {
  it("runs over the stored sessions and writes the report", () => {
    const files = readdirSync(DIR!).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort();
    expect(files.length).toBeGreaterThan(0);
    const days: DayFile[] = files.map((f) => JSON.parse(readFileSync(`${DIR}/${f}`, "utf8")) as DayFile);
    const nFit = Math.ceil(days.length * 0.6);
    const fitDays = new Set(days.slice(0, nFit).map((d) => d.day));
    const lines: string[] = [];
    const L = (s = "") => lines.push(s);
    L("# Smart OI divergence indicators: research on stored sessions");
    L();
    L(`Generated by \`frontend/src/test/smart-oi-research.test.ts\` from ${days.length} stored sessions (${days.map((d) => d.day).join(", ")}). The first ${nFit} sessions are the fitting set, the last ${days.length - nFit} the judging set: no threshold was tuned on the judging set. Signals are taken at the candle they are confirmed on, without looking at what happened after; a flow divergence that later fails still counts as a signal.`);
    L();
    L("Read-only measurement. A signal is judged by the move of the NIFTY close after it (forward return) against the same move after every candle of the same sessions (the baseline). The hit rate of a bullish signal is the share of cases where price was higher after the horizon; of a bearish signal, lower. The interval is a Wilson 95 % interval. **Verdict** needs at least 30 judging-set cases and the whole interval above the baseline hit rate; otherwise the indicator stays \"not validated\".");
    L();
    for (const tf of TFS) {
      const obs: Obs[] = [];
      const base: Record<number, { up: number; down: number; n: number; abs: number[] }> = {};
      for (const h of HORIZONS) base[h] = { up: 0, down: 0, n: 0, abs: [] };
      const baseJudge: typeof base = {};
      for (const h of HORIZONS) baseJudge[h] = { up: 0, down: 0, n: 0, abs: [] };
      let candlesTotal = 0, compositeObs: { day: string; dir: "bullish" | "bearish"; ret: Record<number, number | null> }[] = [];
      for (const d of days) {
        const res = smartOiCandles(d.oi, tf, { openMin: 555, closeMin: 940 });
        if (res.candles.length < 10) continue;
        candlesTotal += res.candles.length;
        const flow = d.strikes ? buildStrikeFlow(res, d.strikes, 555) : undefined;
        const rep = analyseSmartOi(res, { strikeFlow: flow, future: d.future && d.future.times?.length ? alignFuture(res, d.future) : undefined });
        const close = res.candles.map((c) => c.spot?.close ?? null);
        const fwd = (i: number, h: number): number | null => {
          const j = i + candlesFor(tf, h), a = close[i], b = close[j];
          return a != null && b != null && a > 0 ? b / a - 1 : null;
        };
        const isFit = fitDays.has(d.day);
        for (let i = 4; i < res.candles.length; i++) for (const h of HORIZONS) {
          const r = fwd(i, h);
          if (r == null) continue;
          for (const bag of isFit ? [base] : [base, baseJudge]) { bag[h]!.n++; if (r > 0) bag[h]!.up++; if (r < 0) bag[h]!.down++; bag[h]!.abs.push(Math.abs(r)); }
        }
        // one case per indicator and direction per burst: a signal that repeats within 3 candles is the same event
        const last = new Map<string, number>();
        for (const s of rep.signals as Signal[]) {
          const key = `${s.id}|${s.direction}`;
          if (last.has(key) && s.i - last.get(key)! <= 3) { last.set(key, s.i); continue; }
          last.set(key, s.i);
          obs.push({ day: d.day, id: s.id, dir: s.direction, ret: Object.fromEntries(HORIZONS.map((h) => [h, fwd(s.i, h)])) });
        }
        // composite: readings active at candle i are each indicator's latest signal within the window
        const w = candlesFor(tf, TH.windowMin);
        let lastDir: string | null = null;
        for (let i = w; i < res.candles.length; i++) {
          const rd: Reading[] = (["flow", "writing", "conviction", "pcr", "future", "zone", "momentum"] as const).map((id) => {
            const cur = [...(rep.signals as Signal[])].reverse().find((s) => s.id === id && s.i <= i && s.i > i - w);
            return { id, active: !!cur, direction: cur?.direction ?? "neutral", strength: cur?.strength ?? 0, at: cur?.at ?? null, text: "" };
          });
          const c = composeOf(rd, "A");
          const dir = c.direction === "neutral" ? null : c.direction;
          if (dir && dir !== lastDir) compositeObs.push({ day: d.day, dir, ret: Object.fromEntries(HORIZONS.map((h) => [h, fwd(i, h)])) });
          lastDir = dir;
        }
      }
      L(`## ${tf}-minute candles`);
      L();
      L(`${candlesTotal} candles; baseline (every candle): ${HORIZONS.map((h) => `${h} min: up ${pc(base[h]!.n ? base[h]!.up / base[h]!.n : null)}, down ${pc(base[h]!.n ? base[h]!.down / base[h]!.n : null)}, mean |move| ${bp(mean(base[h]!.abs))} bp`).join("; ")}.`);
      L();
      const row = (label: string, rows: Obs[], dir: "bullish" | "bearish", h: number, bg: typeof base) => {
        const rr = rows.filter((o) => o.dir === dir && o.ret[h] != null);
        const k = rr.filter((o) => (dir === "bullish" ? o.ret[h]! > 0 : o.ret[h]! < 0)).length;
        const [lo, hi] = wilson(k, rr.length);
        const b = bg[h]!, bh = b.n ? (dir === "bullish" ? b.up : b.down) / b.n : null;
        const dm = mean(rr.map((o) => (dir === "bullish" ? o.ret[h]! : -o.ret[h]!)));
        return { text: `| ${label} | ${dir} | ${h} | ${rr.length} | ${rr.length ? pc(k / rr.length) : "—"} | ${rr.length ? `${pc(lo)} to ${pc(hi)}` : "—"} | ${pc(bh)} | ${bp(dm)} | ${rr.length >= 30 && bh != null && lo > bh ? "supported" : rr.length < 30 ? "too few cases" : "not supported"} |`, ok: rr.length >= 30 && bh != null && lo > bh };
      };
      const head = "| Indicator | Direction | Horizon (min) | Cases | Hit rate | 95 % interval | Baseline | Mean directional move (bp) | Verdict |\n|---|---|---|---|---|---|---|---|---|";
      for (const [title, set, bg] of [["All sessions", obs, base], ["Judging sessions only", obs.filter((o) => !fitDays.has(o.day)), baseJudge]] as const) {
        L(`### ${title}`);
        L();
        L(head);
        for (const id of ["flow", "writing", "conviction", "pcr", "future", "zone", "momentum"] as const)
          for (const dir of ["bullish", "bearish"] as const) for (const h of HORIZONS) {
            const rows = set.filter((o) => o.id === id);
            if (rows.some((o) => o.dir === dir)) L(row(INDICATOR_NAMES[id], rows, dir, h, bg).text);
          }
        const cset = (title.startsWith("All") ? compositeObs : compositeObs.filter((o) => !fitDays.has(o.day))).map((o) => ({ ...o, id: "composite" }));
        for (const dir of ["bullish", "bearish"] as const) for (const h of HORIZONS) if (cset.some((o) => o.dir === dir)) L(row("Composite (3+ agree)", cset as unknown as Obs[], dir, h, bg).text);
        L();
      }
    }
    L("## What this does and does not show");
    L();
    L(`- ${days.length} sessions is a small sample: most indicators have too few cases to be judged, and the verdict says so instead of rounding up. More sessions are stored every day; re-run this after each week.`);
    L("- Cases inside one session are not independent (a trending day gives many similar signals): the intervals are narrower than the real uncertainty.");
    L("- The forward move is measured on the NIFTY close of the candle grid, before costs. Nothing here is an order, a target or a recommendation.");
    L("- Neutral signals (absorption, unusual Smart OI) have no direction and are not judged here.");
    if (OUT) writeFileSync(OUT, lines.join("\n") + "\n");
    expect(lines.length).toBeGreaterThan(10);
  });
});

describe("research helpers", () => {
  it("Wilson interval: 60 of 100 is 0.502 to 0.691", () => {
    const [lo, hi] = wilson(60, 100);
    expect(lo).toBeCloseTo(0.5020, 3); expect(hi).toBeCloseTo(0.6910, 3);
    expect(wilson(0, 0)).toEqual([0, 1]);
    expect(existsSync(".")).toBe(true);
  });
});
