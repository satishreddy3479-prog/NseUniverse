def test_missing_strikes_crossed_books_one_sided_chains_and_the_final_second() -> None:
    gappy = tuple(q for q in smile_quotes(T1, P1) if not (25550.0 <= q.strike <= 25700.0))  # a hole in the chain
    s = build_surface([ExpiryInput("2026-11-23", T1, R, gappy, F)], NOW).slices[0]
