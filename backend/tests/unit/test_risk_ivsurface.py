    crossed = [dataclasses.replace(q, bid=(q.ask or 0.0) + 1.0) if q.strike == 25500.0 else q for q in smile_quotes(T1, P1)]
    rows = build_surface([ExpiryInput("2026-11-23", T1, R, tuple(crossed), F)], NOW).strikes
    assert {x.reason for x in rows if x.strike == 25500.0} == {"crossed book"}
    calls_only = tuple(q for q in smile_quotes(T1, P1) if q.cp == CALL)  # no puts at all: a forward must be supplied, and in-the-money calls are used where they are the only side
    none = build_surface([ExpiryInput("2026-11-23", T1, R, calls_only, None)], NOW).slices[0]
    assert none.params is None and none.forward_source == "none" and none.degraded_reason == "no forward"
