# ------------------------------------------------------------------ speed (generous limits; the real numbers are reported with the checkpoint)
def test_the_surface_builds_fast_enough() -> None:
    exps = two_expiries()
    t0 = time.perf_counter()
    cold = build_surface(exps, NOW)
    cold_ms = (time.perf_counter() - t0) * 1000
    t1 = time.perf_counter()
    build_surface(exps, NOW, previous=cold)
    warm_ms = (time.perf_counter() - t1) * 1000
    assert cold_ms < 1500 and warm_ms < 1000
