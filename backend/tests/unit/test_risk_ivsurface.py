# ------------------------------------------------------------------ rebuild debounce
def test_the_scheduler_rebuilds_on_enough_changes_or_on_the_interval_and_never_without_changes() -> None:
    now = [100.0]
    sch = RebuildScheduler(10, 0.3, lambda: now[0])
    assert not sch.due()  # nothing changed
    sch.note_changes(1)
    assert sch.due()  # the very first build is due as soon as there is anything
    sch.mark_rebuilt()
    sch.note_changes(3)
    assert not sch.due()  # three strikes and 0 s since the last rebuild
    now[0] += 0.29
    assert not sch.due()
    now[0] += 0.02
    assert sch.due()  # 0.31 s with something changed
    sch.mark_rebuilt()
    now[0] += 5.0
    assert not sch.due()  # a long quiet period alone is not a reason
    sch.note_changes(9)
    assert not sch.due() or now[0] - 100.0 > 0
    sch.mark_rebuilt()
    sch.note_changes(4)
    sch.note_changes(6)
    assert sch.pending == 10 and sch.due()  # ten changed strikes: rebuild at once


