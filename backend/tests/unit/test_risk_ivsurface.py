def test_brent_finds_roots_and_refuses_an_unbracketed_one() -> None:
    root, n = brent(lambda x: x**3 - 2.0, 1.0, 2.0)
    assert root == pytest.approx(2.0 ** (1 / 3), abs=1e-12) and n < 20
    assert brent(lambda x: x, -1.0, 0.0)[0] == 0.0  # an end point that is a root
    with pytest.raises(ValueError):
        brent(lambda x: x * x + 1.0, -1.0, 1.0)


def test_the_seed_by_hand_and_the_scalar_price_equal_the_vectorised_pricer() -> None:
    # F = K = 100, T = 0.25, r = 0, sigma = 0.2: d1 = 0.05, price = 100 (2 N(0.05) - 1) = 100 (2 * 0.519939 - 1) = 3.98776; seed = sqrt(2 pi / 0.25) * 3.98776 / 100 = 5.013257 * 0.0398776 = 0.199916 (0.04 % from 0.2)
    price = float(black76(CALL, 100.0, 100.0, 0.25, 0.2, 0.0))
    assert price == pytest.approx(3.98776, abs=1e-5)
    assert seed_brenner_subrahmanyam(CALL, price, 100.0, 100.0, 0.25, 0.0) == pytest.approx(0.199916, abs=2e-6)
    rng = np.random.default_rng(3)
    for _ in range(200):
        cp, k, t, s = (CALL, PUT)[int(rng.integers(2))], F * math.exp(rng.uniform(-0.1, 0.1)), float(rng.uniform(0.001, 1.0)), float(rng.uniform(0.05, 1.0))
        assert price_scalar(cp, F, k, t, s, R) == pytest.approx(float(black76(cp, F, k, t, s, R)), rel=1e-12, abs=1e-12)


def test_prices_from_a_known_volatility_invert_back_across_strikes_and_expiries() -> None:
    rng = np.random.default_rng(11)
    worst_price, worst_iv, count = 0.0, 0.0, 0
    for _ in range(1500):
        t = float(np.exp(rng.uniform(math.log(1e-4), math.log(1.5))))
        s = float(rng.uniform(0.06, 0.9))
        k = F * math.exp(float(rng.uniform(-3.0, 3.0)) * s * math.sqrt(t))  # within three standard deviations
        cp = (CALL, PUT)[int(rng.integers(2))]
        p = float(black76(cp, F, k, t, s, R))
        res = implied_vol(cp, p, F, k, t, R)
        assert res.status == "ok", (cp, k, t, s, p)
        count += 1
        worst_price = max(worst_price, abs(float(black76(cp, F, k, t, res.iv, R)) - p) / p)
        if p > 1e-3 * F * s * math.sqrt(t):  # where the price carries information the volatility itself is recovered
            worst_iv = max(worst_iv, abs(res.iv - s) / s)
    assert count == 1500 and worst_price < 1e-9 and worst_iv < 1e-7


def test_the_solver_says_why_there_is_no_volatility() -> None:
    assert implied_vol(CALL, 99.9, F, 25400.0, 0.01, R).status == "no_time_value"  # the discounted intrinsic value of a 100-point in-the-money call is 100 e^(-0.065 * 0.01) = 99.935
    assert implied_vol(CALL, F, F, 25400.0, 0.01, R).status == "above_bound"  # a call cannot be worth the whole forward
    assert implied_vol(PUT, 3.0, F, 25000.0, 0.01, R, DEFAULT).status in ("ok", "no_time_value")
    assert implied_vol(CALL, -1.0, F, F, 0.01, R).status == "invalid" and implied_vol(CALL, 5.0, F, F, 0.0, R).status == "invalid"
    assert implied_vol(CALL, 5.0, np.nan, F, 0.01, R).status == "invalid" and implied_vol(0.0, 5.0, F, F, 0.01, R).status == "invalid"
    assert implied_vol(CALL, 5.0, F, F, DEFAULT.t_floor_years * 0.5, R).status == "invalid"
    assert math.isnan(implied_vol(CALL, 99.9, F, 25400.0, 0.01, R).iv)
    assert implied_vol(CALL, 100.0, F, 25400.0, 0.01, R).status == "ok"  # 100 is above the discounted intrinsic value: a tiny time value, so a (very small) volatility


