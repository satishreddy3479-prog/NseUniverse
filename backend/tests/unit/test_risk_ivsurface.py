# ------------------------------------------------------------------ forward and arbitrage tests
def smile_quotes(t: float, p: SVIParams, strikes: np.ndarray | None = None, spread: float = 0.01, forward: float = F) -> tuple[Quote, ...]:
    ks = np.arange(24500.0, 26500.1, 50.0) if strikes is None else strikes
    out: list[Quote] = []
    for k in ks:
        iv = float(p.implied_vol(math.log(k / forward), t))
        for cp in (CALL, PUT):
            px = float(black76(cp, forward, float(k), t, iv, R))
            h = max(px * spread / 2.0, 0.025)
            out.append(Quote(float(k), cp, px - h, px + h, px))
    return tuple(out)


def test_parity_forward_recovers_the_forward_from_prices() -> None:
    t = T1
    prices = {(float(k), cp): float(black76(cp, 25512.0, float(k), t, 0.15, R)) for k in range(25300, 25800, 50) for cp in (CALL, PUT)}
    got = parity_forward(prices, t, R, 3)
    assert got is not None and got[1] == 3 and got[0] == pytest.approx(25512.0, abs=1e-6)
    assert parity_forward({(25500.0, CALL): 100.0}, t, R) is None  # no strike with both sides


def test_arbitrage_flags_name_the_strike_and_the_rule() -> None:
    k = [25400.0, 25450.0, 25500.0, 25550.0, 25600.0]
    calls = [float(black76(CALL, F, x, T1, 0.15, R)) for x in k]
    df = math.exp(-R * T1)
    assert arbitrage_flags(k, calls, df, 0.05) == {}  # a model smile is clean
    bumped = list(calls)
    bumped[2] += 8.0  # a 25500 call worth 8 rupees more than the model: convexity broken at that strike
    assert arbitrage_flags(k, bumped, df, 0.05).get(25500.0, "").startswith("butterfly")
    vertical = list(calls)
    vertical[3] = vertical[2] + 1.0  # a call that rises with the strike
    assert "rises with the strike" in arbitrage_flags(k, vertical, df, 0.05)[25550.0]
    steep = list(calls)
    steep[1] = steep[0] - 80.0  # falls by more than df * 50
    assert "faster than the discounted strike gap" in arbitrage_flags(k, steep, df, 0.05)[25450.0]


# ------------------------------------------------------------------ SVI
def test_nelder_mead_finds_the_minimum_of_a_quadratic_and_of_rosenbrock() -> None:
    x, val, _ = nelder_mead(lambda z: float((z[0] - 1.5) ** 2 + 3.0 * (z[1] + 0.5) ** 2), np.array([0.0, 0.0]), np.array([0.5, 0.5]))
    assert x == pytest.approx([1.5, -0.5], abs=1e-5) and val < 1e-10
    x2, _, _ = nelder_mead(lambda z: float(100 * (z[1] - z[0] ** 2) ** 2 + (1 - z[0]) ** 2), np.array([-1.0, 1.0]), np.array([0.3, 0.3]), max_iter=400)
    assert x2 == pytest.approx([1.0, 1.0], abs=1e-3)


def test_svi_density_detects_butterfly_arbitrage_in_a_known_bad_smile() -> None:
    k = np.linspace(-1.2, 1.2, 481)
    assert float(np.min(P1.density(np.linspace(-0.3, 0.3, 301)))) > 0.2  # the smile used here is clean
    vogt = SVIParams(a=-0.0410, b=0.1331, rho=0.3060, m=0.3586, sigma=0.4153)  # Gatheral and Jacquier 2014, example 3.1 (Vogt): known to have negative density
    assert float(np.min(vogt.density(k))) < 0.0


def test_svi_fit_recovers_known_parameters_and_is_arbitrage_free() -> None:
    k = np.linspace(-0.06, 0.06, 41)
    fit = fit_svi(k, P1.total_variance(k), np.ones_like(k))
    p = fit.params
    assert (p.a, p.b, p.rho, p.m, p.sigma) == pytest.approx((P1.a, P1.b, P1.rho, P1.m, P1.sigma), rel=1e-5, abs=1e-7)
    assert fit.rms_total_variance < 1e-12 and fit.butterfly_ok and fit.min_density > 0.2
    assert p.b * (1 + abs(p.rho)) <= 2.0 and p.a + p.b * p.sigma * math.sqrt(1 - p.rho**2) >= 0.0  # Lee's bound and non-negative minimum variance
    warm = fit_svi(k, P1.total_variance(k), np.ones_like(k), warm=p)
    assert warm.params.m == pytest.approx(p.m, abs=1e-6) and warm.iterations <= fit.iterations  # a warm start from the answer needs no more work


def test_svi_fit_holds_the_constraints_on_noisy_data_and_few_points() -> None:
    rng = np.random.default_rng(5)
    k = np.linspace(-0.08, 0.08, 31)
    iv = P1.implied_vol(k, T1) * (1.0 + 0.02 * rng.standard_normal(k.size))  # two percent of noise in volatility
    fit = fit_svi(k, iv**2 * T1, np.ones_like(k))
    assert fit.butterfly_ok and fit.min_density > -1e-6 and fit.params.b >= 0 and abs(fit.params.rho) < 1 and fit.params.sigma > 0
    with pytest.raises(ValueError):
        fit_svi(k[:4], iv[:4] ** 2 * T1, np.ones(4))


def test_calendar_violation_is_the_largest_shortfall() -> None:
    k = np.linspace(-0.1, 0.1, 21)
    assert calendar_violation(P1, P2, k) == 0.0  # the farther expiry has more total variance everywhere
    assert calendar_violation(P2, P1, k) == pytest.approx(float(np.max(P2.total_variance(k) - P1.total_variance(k))), rel=1e-12)


# ------------------------------------------------------------------ the surface
def two_expiries(**over: object) -> list[ExpiryInput]:
    return [
        ExpiryInput("2026-11-23", T1, R, smile_quotes(T1, P1), None),
        ExpiryInput("2026-11-30", T2, R, smile_quotes(T2, P2), None),
    ]


def test_a_surface_built_from_known_smiles_recovers_forward_and_parameters() -> None:
    snap = build_surface(two_expiries(), NOW)
    near, far = snap.slices
    for s, p in ((near, P1), (far, P2)):
        assert s.forward == pytest.approx(F, abs=0.05) and s.forward_source == "parity(3)"
        assert s.params is not None and (s.params.b, s.params.rho, s.params.m, s.params.sigma) == pytest.approx((p.b, p.rho, p.m, p.sigma), rel=0.03, abs=2e-3)
        assert s.rms_vol_pts < 0.05 and not s.degraded and s.butterfly_ok and s.calendar_ok and s.min_density > 0.2
    k = np.array([-0.03, 0.0, 0.03])
    assert snap.iv("2026-11-23", k) == pytest.approx(P1.implied_vol(k, T1), abs=2e-4)  # the fitted volatility at three log-moneyness points
    assert far.t_years > near.t_years and snap.slices[0].expiry == "2026-11-23"
    used = [x for x in snap.strikes if x.status == "used"]
    assert len(used) == 82 - 6 and all(abs(x.residual_vol_pts) < 0.1 for x in used)  # 41 strikes in each expiry, the out-of-the-money side of each, less six far-wing strikes of the near expiry whose book is too wide
    assert all(x.source == "mid" and x.weight == 1.0 for x in used)
    fwd = {s.expiry: s.forward for s in snap.slices}
    sides = {(x.strike >= fwd[x.expiry]) == (x.cp == CALL) for x in used}
    assert sides == {True}  # calls from the forward up, puts below it
    unused = [x for x in snap.strikes if x.status == "unused"]
    assert unused and all(x.reason in ("other side kept (out of the money preferred)", "out-of-the-money side rejected: in-the-money price not used") for x in unused)
    assert sum(x.reason == "other side kept (out of the money preferred)" for x in unused) == 76  # one unused quote per kept strike; the rest are the in-the-money sides of the six dropped wing strikes


def test_wide_spread_quotes_are_rejected_with_their_reason_and_not_fitted() -> None:
    snap = build_surface(two_expiries(), NOW)
    rej = [x for x in snap.strikes if x.status == "rejected"]
    assert rej and all(x.reason == "spread above 15% of the mid" and math.isnan(x.iv) and math.isnan(x.residual_vol_pts) for x in rej)
    assert all(abs(x.strike - F) > 800 for x in rej)  # the far wings, where a rupee-wide book is a large share of a tiny price
    assert sum(s.n_rejected for s in snap.slices) == len(rej)


def test_versions_are_deterministic_content_hashes_and_snapshots_are_immutable() -> None:
    a = build_surface(two_expiries(), NOW, seq=7)
    b = build_surface(two_expiries(), NOW.replace(hour=15), seq=8)  # the same quotes at another time and sequence number
    assert a.content_hash == b.content_hash and a.version_id == f"v7-{a.content_hash}" and b.version_id == f"v8-{a.content_hash}"
    assert a.as_of_ist == "2026-11-20T11:00:00+05:30"
    changed = two_expiries()
    q = list(changed[0].quotes)
    q[10] = dataclasses.replace(q[10], bid=(q[10].bid or 0.0) + 0.01)
    changed[0] = dataclasses.replace(changed[0], quotes=tuple(q))
    assert build_surface(changed, NOW, seq=7).content_hash != a.content_hash  # one price moved by a paisa: a new surface
    assert build_surface(two_expiries(), NOW, SurfaceConfig(spread_threshold_pct=10.0)).content_hash != a.content_hash  # the configuration is part of the version
    with pytest.raises(dataclasses.FrozenInstanceError):
        a.version_id = "x"  # type: ignore[misc]
    with pytest.raises(dataclasses.FrozenInstanceError):
        a.slices[0].forward = 1.0  # type: ignore[misc]
    assert isinstance(a.slices, tuple) and isinstance(a.strikes, tuple)
    with pytest.raises(ValueError):
        build_surface(two_expiries(), datetime(2026, 11, 20, 11, 0))
    # the same inputs give the same numbers, warm start or not
    warm = build_surface(two_expiries(), NOW, previous=a)
    assert warm.slices[0].params is not None and a.slices[0].params is not None and warm.slices[0].params.b == pytest.approx(a.slices[0].params.b, rel=1e-4)


def test_a_quote_that_breaks_convexity_is_flagged_listed_and_left_out_of_the_fit() -> None:
    qs = list(smile_quotes(T1, P1))
    i = next(j for j, q in enumerate(qs) if q.strike == 25700.0 and q.cp == CALL)
    qs[i] = dataclasses.replace(qs[i], bid=(qs[i].bid or 0.0) + 6.0, ask=(qs[i].ask or 0.0) + 6.0)  # a 25,700 call priced 6 rupees too high
    snap = build_surface([ExpiryInput("2026-11-23", T1, R, tuple(qs), None)], NOW)
    flagged = [x for x in snap.strikes if x.status == "flagged"]
    assert [(x.strike, x.cp) for x in flagged] == [(25700.0, CALL)] and flagged[0].reason is not None and flagged[0].reason.startswith("butterfly")
    assert math.isfinite(flagged[0].residual_vol_pts) and flagged[0].residual_vol_pts > 0.3  # its market volatility is above the fit, and the number is shown
    s = snap.slices[0]
    assert s.n_flagged == 1 and s.params is not None and s.rms_vol_pts < 0.05  # the fit of the others is untouched by it
    assert s.params.b == pytest.approx(P1.b, rel=0.03)


def test_noise_too_few_points_and_calendar_violations_mark_the_expiry_degraded() -> None:
    rng = np.random.default_rng(9)
    noisy: list[Quote] = []
    for q in smile_quotes(T1, P1):
        mid = 0.5 * ((q.bid or 0.0) + (q.ask or 0.0)) * (1.0 + 0.06 * rng.standard_normal())  # six percent price noise
        noisy.append(dataclasses.replace(q, bid=mid * 0.995, ask=mid * 1.005))
    s = build_surface([ExpiryInput("2026-11-23", T1, R, tuple(noisy), F)], NOW).slices[0]
    assert s.degraded and s.degraded_reason is not None and "residual" in s.degraded_reason and s.rms_vol_pts > 0.5 or s.n_flagged > 0
    few = smile_quotes(T1, P1, np.array([25400.0, 25500.0, 25600.0]))
    t = build_surface([ExpiryInput("2026-11-23", T1, R, few, F)], NOW).slices[0]
    assert t.params is None and t.degraded and t.degraded_reason is not None and "usable points" in t.degraded_reason and t.n_used == 0 and math.isnan(t.rms_vol_pts)
    hi = SVIParams(P1.a * 2.0, P1.b * 2.0, P1.rho, P1.m, P1.sigma)  # the nearer expiry carries twice the total variance of the farther one
    lo = SVIParams(P1.a * 0.5, P1.b * 0.5, P1.rho, P1.m, P1.sigma)
    bad = build_surface([ExpiryInput("2026-11-23", T1, R, smile_quotes(T1, hi), F), ExpiryInput("2026-11-30", T2, R, smile_quotes(T1, lo), F)], NOW)
    far = bad.slices[1]
    assert (not far.calendar_ok and far.calendar_max_violation > 0.0 and far.degraded) or far.rms_vol_pts > 0.5


