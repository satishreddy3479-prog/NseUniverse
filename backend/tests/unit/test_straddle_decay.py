"""Straddle decay intelligence: Shapley attribution, efficiency classes, realised vol, and a synthetic session whose answer is known in advance.

The attribution tests use prices generated by the Black-76 formula itself, so each case isolates one factor and the expected split is exact:
time alone must be all theta, a vol change alone all vega, a forward move alone delta + gamma (gamma positive for a long option), and the five terms
must always add up to the market change.
"""

from __future__ import annotations

import math
from datetime import date, datetime, timedelta
from zoneinfo import ZoneInfo

import pytest

from app.intelligence import straddle as sd
from app.intraday.volatility import CALL, PUT, TRADING_MINUTES_PER_YEAR, price, years_to_expiry

IST = ZoneInfo("Asia/Kolkata")
EXPIRY = date(2026, 11, 12)
OPEN = datetime(2026, 11, 11, 9, 16, tzinfo=IST)
STRIKES = [23800.0 + 50 * i for i in range(13)]
R = 0.06


def chain(at: datetime, spot: float, iv: float, oi: int = 1000) -> sd.Snap:
    """A full chain priced with Black-76 at one flat vol; the forward is spot x carry so parity gives it back."""
    t = years_to_expiry(EXPIRY, at)
    f = spot * math.exp(R * t)
    prices = {(k, s): price(s, f, k, t, iv, R) for k in STRIKES for s in (CALL, PUT)}
    return sd.Snap(at, spot, prices, {key: oi for key in prices})


def session(spots: list[float], ivs: list[float], minutes: int = 1) -> list[sd.Snap]:
    return [chain(OPEN + timedelta(minutes=minutes * i), s, v) for i, (s, v) in enumerate(zip(spots, ivs, strict=True))]


def point(spot: float, iv: float, at: datetime) -> sd.Point:
    p, why = sd.build_point(chain(at, spot, iv), EXPIRY, R)
    assert p is not None, why
    return p


class TestAttribution:
    def test_time_alone_is_all_theta(self) -> None:
        a, b = point(24000, 0.15, OPEN), point(24000, 0.15, OPEN + timedelta(minutes=30))
        # same spot, but the parity forward moves with time (carry), so use the forward-neutral check on vega/residual only
        for side in (CALL, PUT):
            x = sd.attribute_leg(a, b, 24000.0, side)
            assert x is not None
            assert x["vega"] == pytest.approx(0, abs=1e-6)
            assert x["theta"] < 0
            assert x["residual"] == pytest.approx(0, abs=1e-5)
        both = sd.attribute_leg(a, b, 24000.0, CALL)["theta"] + sd.attribute_leg(a, b, 24000.0, PUT)["theta"]  # type: ignore[index]
        # an ATM straddle is ~ proportional to sqrt(T): over dT of T it loses about P x dT / (2T)
        straddle = a.leg(24000.0, CALL).price + a.leg(24000.0, PUT).price  # type: ignore[union-attr]
        expect = -straddle * (a.t - b.t) / (2 * a.t)
        assert both == pytest.approx(expect, rel=0.08)

    def test_vol_alone_is_all_vega(self) -> None:
        a = point(24000, 0.15, OPEN)
        b = point(24000, 0.17, OPEN)  # identical time and spot: only the vol differs
        x = sd.attribute_leg(a, b, 24000.0, CALL)
        assert x is not None
        assert x["theta"] == pytest.approx(0, abs=1e-9)
        assert x["delta"] == pytest.approx(0, abs=1e-9)
        assert x["gamma"] == pytest.approx(0, abs=1e-9)
        assert x["vega"] == pytest.approx(x["actual"], abs=1e-6)
        assert x["vega"] > 0

    def test_forward_alone_is_delta_plus_positive_gamma(self) -> None:
        a = point(24000, 0.15, OPEN)
        b = point(24100, 0.15, OPEN)
        for side in (CALL, PUT):
            x = sd.attribute_leg(a, b, 24000.0, side)
            assert x is not None
            assert x["theta"] == pytest.approx(0, abs=1e-6)
            assert x["vega"] == pytest.approx(0, abs=1e-6)
            assert x["gamma"] > 0  # a long option gains convexity on a move either way
            assert x["delta"] + x["gamma"] == pytest.approx(x["actual"], abs=1e-6)
        ce, pe = sd.attribute_leg(a, b, 24000.0, CALL), sd.attribute_leg(a, b, 24000.0, PUT)
        assert ce["delta"] > 0 > pe["delta"]  # type: ignore[index]
        # gamma ~ half gamma x dF^2 on the call: delta-gamma Taylor check within 15 %
        g = a.leg(24000.0, CALL).g.gamma  # type: ignore[union-attr]
        assert ce["gamma"] == pytest.approx(0.5 * g * (b.f - a.f) ** 2, rel=0.15)  # type: ignore[index]

    def test_all_three_move_and_terms_add_up(self) -> None:
        a, b = point(24000, 0.15, OPEN), point(24060, 0.165, OPEN + timedelta(minutes=20))
        for side in (CALL, PUT):
            x = sd.attribute_leg(a, b, 24000.0, side)
            assert x is not None
            assert sum(x[c] for c in sd.COMPONENTS) == pytest.approx(x["actual"], abs=1e-9)
            assert abs(x["residual"]) < 1e-5  # implied vols are solved from the end prices: only solver error is left

    def test_missing_price_gives_no_attribution(self) -> None:
        a = point(24000, 0.15, OPEN)
        snap = chain(OPEN + timedelta(minutes=1), 24000, 0.15)
        prices = dict(snap.prices) | {(24000.0, PUT): None}
        b, _ = sd.build_point(sd.Snap(snap.at, snap.spot, prices, snap.oi), EXPIRY, R)
        assert b is not None
        assert sd.attribute_leg(a, b, 24000.0, PUT) is None
        steps, skipped = sd.attribute_steps([a, b], [24000.0, 24000.0])
        assert steps[1] is None and skipped == 1


class TestEfficiency:
    def test_classes(self) -> None:
        assert [sd.classify(x) for x in (130, 75, 74.9, 20, 19.9, 0, -9.9, -10, -50, None)] == [
            "efficient", "efficient", "slower", "slower", "none", "none", "none", "expansion", "expansion", "unavailable"]  # fmt: skip

    def test_hand_example_and_reason(self) -> None:
        tot = {"theta": -10.0, "vega": 4.0, "delta": 0.5, "gamma": 1.0, "residual": 0.0, "actual": -5.5}  # market -5.5 = -10 + 4 + 0.5 + 1
        e = sd.efficiency(tot)
        assert e["efficiency_pct"] == 55.0  # 5.5 of 10
        assert e["status"] == "slower"
        assert "IV expansion" in e["reason"]
        assert e["shortfall"] == 4.5

    def test_expansion_and_unavailable(self) -> None:
        e = sd.efficiency({"theta": -4.0, "vega": 1.0, "delta": 0.0, "gamma": 5.0, "residual": 0.0, "actual": 2.0})
        assert e["status"] == "expansion" and "gamma" in e["reason"]
        assert sd.efficiency(None)["status"] == "unavailable"


class TestRealised:
    def test_constant_return(self) -> None:
        spots = [24000 * math.exp(0.001 * i) for i in range(70)]
        times = [OPEN + timedelta(minutes=i) for i in range(70)]
        r = sd.realised(times, spots, 30)
        assert r["returns"] == 30
        assert r["vol_pct"] == pytest.approx(0.001 * math.sqrt(TRADING_MINUTES_PER_YEAR) * 100, abs=0.01)  # 0.001 x sqrt(94500) = 30.74 %
        assert r["sum_sq"] == pytest.approx(30 * 1e-6)

    def test_window_not_covered_is_missing(self) -> None:
        times = [OPEN + timedelta(minutes=i) for i in range(10)]
        r = sd.realised(times, [24000 + i for i in range(10)], 60)
        assert r["vol_pct"] is None and "covered" in r["note"]

    def test_gaps_are_skipped_not_filled(self) -> None:
        times = [OPEN, OPEN + timedelta(minutes=1), OPEN + timedelta(minutes=2), OPEN + timedelta(minutes=30), OPEN + timedelta(minutes=31), OPEN + timedelta(minutes=32)]
        r = sd.realised(times, [24000, 24010, 24020, 24100, 24110, 24120], None)
        assert r["gaps_skipped"] == 1 and r["returns"] == 4


class TestSyntheticSession:
    """Flat spot and flat vol: the straddle should decay by theta and nothing else. Vol up on a flat spot: premium expansion through vega."""

    def test_pure_decay_is_efficient(self) -> None:
        n = 90
        snaps = session([24000.0] * n, [0.15] * n)
        a = sd.analyse(snaps, [(s.at, s.spot) for s in snaps], EXPIRY, rate=R, now=snaps[-1].at, live=True)
        assert a["status"] == "ok"
        main = a["attribution"]["fixed"]["open"]
        assert main["both"]["vega"] == pytest.approx(0, abs=1e-4)
        assert main["both"]["gamma"] == pytest.approx(0, abs=1e-4)
        assert main["efficiency"]["status"] == "efficient"
        assert main["efficiency"]["efficiency_pct"] == pytest.approx(100, abs=0.5)
        assert main["both"]["residual"] == pytest.approx(0, abs=1e-3)
        tr = a["tracker"]["fixed"]
        assert tr["strike"] == 24000.0 and tr["straddle"]["change"] < 0
        assert a["iv"]["support"]["side"] == "neither"
        assert a["attribution"]["rolling"]["open"]["efficiency"]["status"] == "efficient"

    def test_vol_expansion_supports_premium(self) -> None:
        n = 90
        snaps = session([24000.0] * n, [0.15 + 0.02 * i / (n - 1) for i in range(n)])  # 15 -> 17 vol
        a = sd.analyse(snaps, [(s.at, s.spot) for s in snaps], EXPIRY, rate=R, now=snaps[-1].at)
        main = a["attribution"]["fixed"]["open"]
        assert main["both"]["vega"] > 3
        assert main["efficiency"]["status"] == "expansion"
        assert "IV expansion" in main["efficiency"]["reason"]
        assert a["iv"]["support"]["side"] == "both"
        assert a["iv"]["fixed"]["combined"]["change"] == pytest.approx(2.0, abs=0.05)

    def test_whipsaw_gamma_offsets_theta_and_cumulative_matches(self) -> None:
        n = 90
        spots = [24000.0 + (40 if i % 2 else -40) for i in range(n)]
        snaps = session(spots, [0.15] * n)
        a = sd.analyse(snaps, [(s.at, s.spot) for s in snaps], EXPIRY, rate=R, now=snaps[-1].at)
        main = a["attribution"]["fixed"]["open"]
        assert main["both"]["gamma"] > 0  # realised convexity along the path
        assert main["efficiency"]["efficiency_pct"] < 100
        cum = a["cumulative"]["fixed"]
        assert cum["actual"][-1] == pytest.approx(main["both"]["actual"], abs=0.01)
        assert a["realised_vs_implied"]["windows"]["60"]["vol_pct"] is not None
        assert a["realised_vs_implied"]["gap"]["60"] < 0  # whipsaw: realised far above the 15 % implied

    def test_rolling_and_fixed_are_kept_apart(self) -> None:
        n = 60
        snaps = session([24000.0 + 4 * i for i in range(n)], [0.15] * n)  # drifts 236 points: the ATM strike rolls
        a = sd.analyse(snaps, [(s.at, s.spot) for s in snaps], EXPIRY, rate=R, now=snaps[-1].at)
        assert a["tracker"]["rolling"]["rolls"] >= 4
        assert a["tracker"]["fixed"]["strike"] == 24000.0
        assert a["series"]["rolling"]["strike"][-1] != a["series"]["fixed"]["strike"][-1]
        assert a["attribution"]["rolling"]["open"]["steps"] == n - 1

    def test_unavailable_and_quality(self) -> None:
        a = sd.analyse([], [], EXPIRY)
        assert a["status"] == "unavailable" and a["interpretation"] == []
        snaps = session([24000.0] * 5, [0.15] * 5)
        a = sd.analyse(snaps, [(s.at, s.spot) for s in snaps], EXPIRY, rate=R, now=snaps[-1].at + timedelta(minutes=30))
        assert a["quality"]["stale"] is True and a["quality"]["age_minutes"] == pytest.approx(30 + 0, abs=4.1)
        assert a["attribution"]["fixed"]["60"] is None  # a 60-minute window needs 60 minutes of samples

    def test_reading_answers_each_question_without_a_forecast(self) -> None:
        n = 90
        snaps = session([24000.0] * n, [0.15] * n)
        a = sd.analyse(snaps, [(s.at, s.spot) for s in snaps], EXPIRY, rate=R, now=snaps[-1].at)
        qs = [x["q"] for x in a["interpretation"]]
        for want in ("decaying normally", "IV contraction", "IV expansion", "gamma offsetting", "CE or PE", "favourable"):
            assert any(want in q for q in qs), want
        text = " ".join(x["a"] for x in a["interpretation"]).lower()
        assert not any(w in text for w in ("will ", "buy", "sell now", "recommend"))
        assert a["climate"]["label"] in ("favourable", "mixed", "unfavourable", "unknown")


class TestValidation:
    def test_window_pairs_predict_from_the_start_only(self) -> None:
        n = 100
        snaps = session([24000.0] * n, [0.15] * n)
        w = sd.window_pairs(snaps, EXPIRY, 30, R)
        assert len(w) == 3  # 30-minute windows inside 99 minutes
        for x in w:
            assert x["predicted"] < 0 and x["actual"] == pytest.approx(x["predicted"], abs=0.05)  # flat spot, flat vol: theta is the whole change

    def test_insufficient_history_is_said_plainly(self) -> None:
        n = 100
        snaps = session([24000.0] * n, [0.15] * n)
        v = sd.validate([{"session": "2026-11-11", "expiry": "2026-11-12", "windows": sd.window_pairs(snaps, EXPIRY, 30, R)}])
        assert v["sufficient"] is False and "Insufficient" in v["message"]
        assert v["overall"]["windows"] == 3
        assert v["overall"]["ratio_actual_to_predicted"] == pytest.approx(1.0, abs=0.02)

    def test_sufficient_flag_needs_sessions_and_windows(self) -> None:
        w = [{"predicted": -1.0 - i * 0.01, "actual": -0.8 - i * 0.01} for i in range(6)]
        sessions = [{"session": f"2026-10-{d:02d}", "expiry": "x", "windows": w} for d in range(1, 26)]
        v = sd.validate(sessions)
        assert v["sufficient"] is True and v["overall"]["windows"] == 150
        assert v["earlier_half"]["windows"] and v["later_half"]["windows"]
